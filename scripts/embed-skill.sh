#!/bin/sh
# Builds the phone-use skill into pua (`pua skill install`) from skills/phone-use/SKILL.md.
# `make` runs this; `swift test` fails if the two copies differ.
set -e
cd "$(dirname "$0")/.."
{
  echo '// Generated by scripts/embed-skill.sh from skills/phone-use/SKILL.md. Do not edit.'
  echo 'enum SkillText {'
  echo '    static let markdown = #"""'
  cat skills/phone-use/SKILL.md
  echo '"""#'
  echo '}'
} > Sources/PuaKit/SkillText.swift
